package org.wurbelizer.wurbel;

/**
 * Holds common code for source regions.
 */
public abstract class AbstractSourceRegion implements SourceRegion {

  // netbeans token (split cause netbeans cuts off when reading this source :-))
  private static final String GUARD_LEAD = "//GEN-";
  /**
   * Tag to start a named region.<br>
   * Immediately followed by the guarded region's name.
   */
  public static final String GUARD_BEGIN = GUARD_LEAD + "BEGIN:";

  /**
   * Tag to end a named region.<br>
   * Immediately followed by the guarded region's name.
   */
  public static final String GUARD_END = GUARD_LEAD + "END:";

  /**
   * Creates the text for the generated by comment.
   *
   * @param guardName the name of the guarded section
   * @param wurbletElement the wurblet element
   * @return the comment part
   */
  protected String createCommentGeneratedBy(String guardName, SourceWurbletSubElement wurbletElement) {
    StringBuilder buf = new StringBuilder();
    // don't use a pattern here that may be interpreted as a match by some SourceRegion!
    buf.append("code '").append(guardName).append("' generated");
    boolean first = true;
    while (wurbletElement != null) {
      if (first) {
        buf.append(" by wurblet ");
        first = false;
      }
      else {
        buf.append('/');
      }
      buf.append(wurbletElement.getWurbletName());
      wurbletElement = wurbletElement.getParentWurbletElement();
    }
    return buf.toString();
  }

  /**
   * Checks for the token and assert it's not a region name.
   *
   * @param comment the comment string to check
   * @param token the begin- or end-token
   * @return true if token found
   */
  protected boolean matches(String comment, String token) {
    boolean match = false;
    int ndx;
    while ((ndx = comment.indexOf(token)) > 0) {   // never 0
      if (comment.charAt(ndx - 1) != '\'') {    // not 'token (see createCommentGeneratedBy above)
        match = true;
        break;
      }
      // was a region name, check next
      comment = comment.substring(ndx + token.length());
    }
    return match;
  }

  @Override
  public String toString() {
    return type();
  }
}
