package org.wurbelizer.wurbel;

import org.wurbelizer.misc.Constants;

import java.util.ArrayList;
import java.util.List;
import java.util.Properties;
import java.util.StringTokenizer;

/**
 * A {@code SourceElement} represents a section within a {@link SourceDocument}.
 * <p>
 * Source elements belong to one of five categories (types):
 * <ul>
 * <li>block comment (Type.BLOCK_COMMENT)</li>
 * <li>single line comment (Type.SINGLE_COMMENT)</li>
 * <li>code block (Type.CODE)</li>
 * <li>netbeans guarded section (Type.GUARDED_NETBEANS)</li>
 * <li>other guarded section (Type.GUARDED_OTHER)</li>
 * </ul>
 * Comment blocks or guarded blocks may contain other {@link SourceSubElement}s.
 * There are two kinds of sub elements: single-line and multi-line.
 * Single line sub elements end at the end of the line where they started. A wurblet
 * anchor is a single line sub element. Single line sub elements may be enlarged
 * beyond the end of the line by a continuation line (backslash at the end of line).
 * Multi-line sub elements like here- or property-documents are terminated a special
 * control sequence. Furthermore, all leading comment text starting each line will
 * be cut off and will not become part of the contents of the sub element (works like a
 * rectangular cut).
 *
 * @author harald
 */

public class SourceElement {

  /**
   * type of source element
   */
  public enum Type {
    /** comment block */
    BLOCK_COMMENT,
    /** single line comment */
    SINGLE_COMMENT,
    /** guarded block (region) */
    GUARDED,
    /** source code */
    CODE
  }

  private final SourceDocument doc;                             // the source document
  private final Type type;                                      // the type of the source element
  private final SourceWurbletSubElement parentWurbletElement;   // if generated by another wurblet

  private int begin;                                            // offset in the document
  private int end;                                              // end of the element
  private String guardedName;                                   // the guarded name if this is a guarded section
                                                                // or comment with wurblet directive
  private String firstLineLead;                                 // the string from start of line up to the start of element (lazy)

  private List<SourceWurbletSubElement>  wurblets;              // List of wurblets
  private List<SourceHereSubElement>     hereDocuments;         // List of here-documents
  private List<SourcePropertySubElement> propertyDocuments;     // List of property-documents



  /**
   * Creates a source element.
   *
   * @param doc the source document the element belongs to
   * @param type the element's type
   * @param begin the start of the element within the document
   * @param end the end of the element
   * @param parentWurbletElement the wurblet element that generated this element, null if not generated
   *
   * @throws org.wurbelizer.wurbel.SourceException if creating the element failed
   */
  public SourceElement(SourceDocument doc, Type type, int begin, int end,
                       SourceWurbletSubElement parentWurbletElement) throws SourceException {

    this.doc = doc;
    this.type = type;
    this.begin = begin;
    this.end = end;
    this.parentWurbletElement = parentWurbletElement;

    // scan for wurblets and embedded documents
    scan();

    // apply property documents
    if (containsPropertyDocuments()) {
      Properties props = doc.getProperties();
      for (SourcePropertySubElement propDoc: propertyDocuments) {
        propDoc.scanTo(props);
      }
    }
  }


  /**
   * Scans for sub elements if this is a comment or guarded block.
   *
   * @throws SourceException if scanning failed
   */
  public void scan() throws SourceException {

    if (isComment() || isGuarded())  {

      wurblets          = new ArrayList<>();
      hereDocuments     = new ArrayList<>();
      propertyDocuments = new ArrayList<>();
      String text       = getText();
      int start         = 0;

      // scan for wurblets
      while ((start = text.indexOf("@wurblet", start)) >= 0)  {
        if (start == 0 || text.charAt(start-1) != '\\') {  // if not escaped '\@wurblet'
          // determine comment lead
          String commentLead = null;
          if (type == Type.BLOCK_COMMENT) {
            // go back to line start
            int lineNdx = start;
            while (lineNdx-- >= 0) {
              if (text.charAt(lineNdx) == '\n') {
                lineNdx++;
                commentLead = text.substring(lineNdx, start);
                // lead must contain only whitespaces and a single asterisk
                int asterCount = 0;
                for (int i=0; i < commentLead.length(); i++) {
                  char c = commentLead.charAt(i);
                  if (Character.isWhitespace(c)) {
                    continue;
                  }
                  if (c == '*') {
                    asterCount++;
                  }
                  else {
                    break;
                  }
                }
                if (asterCount != 1) {
                  commentLead = null;
                }
                break;
              }
            }
          }

          // find end which is max up to line-end or concatenated lines via backslash
          int currentEnd = start;
          for (;;)  {
            currentEnd = text.indexOf('\n', currentEnd);
            if (currentEnd == -1)  {
              currentEnd = text.length();    // no line terminator (end of file)
              break;
            }
            else {
              if (currentEnd > 0 && text.charAt(currentEnd - 1) == '\\' ||    // unixes
                  currentEnd > 1 && text.charAt(currentEnd - 2) == '\\' && text.charAt(currentEnd - 1) == '\r') { // windozes
                // continuation line: check next line
                currentEnd++;
              }
              else  {
                // this is the end of line
                break;
              }
            }
          }

          // create new wurblet directive
          wurblets.add(new SourceWurbletSubElement(this, commentLead, begin + start, begin + currentEnd));
          start = currentEnd;
        }
        else  {
          start++;
        }
      }

      // scan for here- and property-documents
      start = 0;
      int hereStart;    // >=0 if Here-Document
      int propStart;    // >=0 if Property-Document

      while ((hereStart = text.indexOf("@>", start)) >= 0 |     // single or! (to process both lines)
             (propStart = text.indexOf("@{", start)) >= 0)  {

        if (hereStart >= 0 && (propStart < 0 || propStart > hereStart)) {
          // process heredoc
          start = hereStart;
          propStart = -1;
        }
        else {
          // process propdoc
          start = propStart;
          hereStart = -1;
        }

        if (start == 0 || text.charAt(start-1) != '\\') {
          // get the length of the leadstring (i.e. back to start of current line)
          int leadNdx = start;
          while (leadNdx >= 0) {
            if (text.charAt(leadNdx) == '\n') {
              // start of line found
              break;
            }
            leadNdx--;
          }
          leadNdx++;
          int leadLen = start - leadNdx;
          if (leadLen < 0)  {
            leadLen = 0;
          }
          // process document text
          int currentEnd = text.indexOf('\n', start);   // get line end
          if (currentEnd >= 0 && currentEnd < text.length() - 1) {
            StringTokenizer stok = new StringTokenizer(text.substring(start + 2, currentEnd));
            if (propStart >= 0 || stok.hasMoreTokens())  {    // property document or next is filename
              String filename = propStart >= 0 ? null : stok.nextToken();
              String hereOption = null;
              if (filename != null && stok.hasMoreTokens()) {
                hereOption = stok.nextToken();
              }
              // get contents
              String body = text.substring(currentEnd + 1); // body = rest of comment block
              int bodyLen = hereStart >= 0 ? body.indexOf("@<") : body.indexOf("@}");
              if (bodyLen <= 0) {
                throw new SourceException(this, "missing '" + (hereStart >= 0 ? "@<" : "@}") + "' in comment block");
              }
              currentEnd += bodyLen;
              if (body.charAt(bodyLen-1) != '\\')  {
                body = body.substring(0, bodyLen);
                // now cut the lead from every line, if any
                if (leadLen > 0)  {
                  StringBuilder buf = new StringBuilder();
                  stok = new StringTokenizer(body, "\n");
                  while (stok.hasMoreTokens())  {
                    String line = stok.nextToken();
                    if (line.length() > leadLen) {
                      line = line.substring(leadLen);
                      buf.append(line);
                    }
                    buf.append('\n');
                  }
                  body = buf.toString();
                }
                if (body.length() > 1)  {   // if at least one empty line
                  if (body.charAt(body.length()-1) == '\n') {
                    body = body.substring(0, body.length() - 1);  // cut last newline
                  }
                  if (hereStart >= 0) {
                    // add the here-Document (escapes of wurblet-characters removed)
                    String hereText = body.replace("\\@", "@");
                    if (hereOption == null || !hereOption.equals("--nosource")) {
                      hereText = Constants.ORIGIN_INFO_LEAD +
                                 doc.getName() +
                                 ":" +
                                 doc.getLineNumber(begin + hereStart) +
                                 "\n" +
                                 hereText;
                    }
                    hereDocuments.add(new SourceHereSubElement(this, filename, hereText));
                  }
                  else  {
                    propertyDocuments.add(new SourcePropertySubElement(this, body.replace("\\@", "@")));
                  }
                }
              }
            }
          }
          start = currentEnd;
        }
        else  {
          start++;
        }
      }
    }
  }


  /**
   * Gets the contents of this element
   *
   * @return the text of this element
   */
  public String getText()  {
    return doc.getText().substring(begin, end);
  }


  /**
   * Gets the string from the beginning of the line, up to this element.
   *
   * @return the lead string, empty if none (never null)
   */
  public String getFirstLineLead() {
    if (firstLineLead == null) {
      // not yet determined: determine index to start of line
      int ndx = begin;
      while (ndx > 0) {
        char c = doc.getText().charAt(--ndx);
        if (c == '\n' || c == '\r') {
          ndx++;
          break;
        }
      }
      firstLineLead = doc.getText().substring(ndx, begin);
    }
    return firstLineLead;
  }


  /**
   * Checks whether this element is a code block.
   *
   * @return true if element contains sourcecode
   */
  public boolean isCode() {
    return type == Type.CODE;
  }


  /**
   * Checks whether this element is a guarded block.
   *
   * @return true if this is a guarded block
   */
  public boolean isGuarded() {
    return type == Type.GUARDED;
  }


  /**
   * Checks whether this element is a comment.
   *
   * @return true if this is a comment
   */
  public boolean isComment()  {
    return type == Type.BLOCK_COMMENT || type == Type.SINGLE_COMMENT;
  }


  /**
   * Checks whether this element contains wurblets.
   *
   * @return true if element contains a wurblet anchors
   */
  public boolean containsWurblets()  {
    return wurblets != null && !wurblets.isEmpty();
  }


  /**
   * Gets the list of wurblets.
   *
   * @return list of wurblets
   */
  public List<SourceWurbletSubElement> getWurblets()  {
    return wurblets;
  }


  /**
   * Checks whether this element contains here-documents.
   *
   * @return true if element contains here-documents
   */
  public boolean containsHereDocuments() {
    return hereDocuments != null && !hereDocuments.isEmpty();
  }


  /**
   * Gets the list of here-documents.
   *
   * @return the list of here-Documents
   */
  public List<SourceHereSubElement> getHereDocuments()  {
    return hereDocuments;
  }


  /**
   * Checks whether this element contains property documents.
   *
   * @return true if element contains property-documents
   */
  public boolean containsPropertyDocuments() {
    return propertyDocuments != null && !propertyDocuments.isEmpty();
  }


  /**
   * Gets the list of property documents.
   *
   * @return the list of property-Documents
   */
  public List<SourcePropertySubElement> getPropertyDocuments()  {
    return propertyDocuments;
  }


  /**
   * Checks whether this element contains only whitespaces.
   *
   * @return true if element contains only whitespaces or newlines
   */
  public boolean isWhiteEmpty() {
    String str = getText();
    int len = str.length();
    for (int i=0; i < len; i++) {
      if (!Character.isWhitespace(str.charAt(i)))  {
        return false;
      }
    }
    return true;
  }


  /**
   * Gets the {@link SourceDocument} this element belongs to.
   *
   * @return the source document
   */
  public SourceDocument getSourceDocument() {
    return doc;
  }


  /**
   * Gets the parent wurblet that generated this element.
   *
   * @return the wurblet, null if not generated
   */
  public SourceWurbletSubElement getParentWurbletElement() {
    return parentWurbletElement;
  }


  /**
   * Gets the type of this source element.
   *
   * @return the type.
   */
  public Type getType() {
    return type;
  }


  /**
   * Gets the start offset of this element within its document.
   *
   * @return the start offset
   */
  public int getBegin() {
    return begin;
  }


  /**
   * Sets the start offset of this element within its document.
   *
   * @param begin the start of this element
   */
  public void setBegin(int begin) {
    this.begin = begin;
  }


  /**
   * Gets the end offset of this element within its document.
   *
   * @return the end of this element
   */
  public int getEnd() {
    return end;
  }


  /**
   * Sets the end offset of this element within its document.
   *
   * @param end the end of this element
   */
  public void setEnd(int end) {
    this.end = end;
  }

  /**
   * Moves the element within the document.
   *
   * @param diff chars to move
   */
  public void move(int diff) {
    begin += diff;
    end += diff;
    if (wurblets != null) {
      for (SourceWurbletSubElement wurblet : wurblets) {
        wurblet.move(diff);
      }
    }
  }


  /**
   * Removes characters in text and updates doc and all other elements.
   *
   * @param startNdx the offset to start (relative to the element)
   * @param endNdx the offset to end (relative to the element)
   */
  public void deleteText(int startNdx, int endNdx)  {
    doc.deleteText(this.begin + startNdx, this.begin + endNdx);
  }


  /**
   * Gets the guarded name if this is a guarded block.
   *
   * @return the guardedname of this comment block
   */
  public String getGuardedName() {
    return guardedName;
  }


  /**
   * Sets the guarded name if this is a guarded block.
   *
   * @param guardedName the guardedname of this comment block
   */
  public void setGuardedName(String guardedName) {
    this.guardedName = guardedName;
  }



  /**
   * Prints the name and line info of the element.
   *
   * @return the string for diagnostics
   */
  @Override
  public String toString()  {
    return doc + " (line " + doc.getLineNumber(begin) + " - " + doc.getLineNumber(end) + ")";
  }


}
