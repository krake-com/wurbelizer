/**
 * Base class for the wurbel mojos.<br>
 * Scans the sources for &#64;wurblet anchors and executes the wurblets.
 * The generated code from the wurblets is merged into the sources.
 *
 * @author harald
 */
public abstract class AbstractWurbelMojo extends AbstractWurbelizerMojo {

  /**
   * Gets the directory holding the sources to be wurbelized.
   *
   * @return the sources directory
   */
  public abstract File getSourceDir();

  /**
   * Gets the directory for additional files generated by preceeding phases
   * provided for wurblets.
   *
   * @return the analyze directory
   */
  public abstract File getAnalyzeDir();

  /**
   * Target directory for all files referenced by wurblets.
   */
  @Parameter(defaultValue = "${project.build.directory}/wurbel",
             property = "wurbel.wurbelDir",
             required = true)
  private File wurbelDir;


  /**
   * Classpaths for loading wurblets.<br>
   * Used for all non-fully-qualified wurblet anchors.
   */
  @Parameter(required = true)
  private List<String> wurbletPaths;

  /**
   * Properties used by wurblets.<br>
   * Properties referring to directories or files should
   * prepend {@code ${wurbelDir}} in their path. This is a predefined
   * property pointing to {@code fileDir}.
   */
  @Parameter
  private Properties wurbletProperties;

  /**
   * Classpaths for loading wurblets.<br>
   * Used for all non-fully-qualified wurblet anchors.
   */
  @Parameter
  private List<WurbletDependency> wurbletDependencies;

  /**
   * Dry run.<br>
   * Don't run the wurblets, just parse the files.
   */
  @Parameter
  private boolean dryRun;


  /**
   * The classrealm.
   * <p>
   * Retrieved if {@code configurator = "set-classrealm"} is set in the &#064;Mojo annotation.
   * @see ClassRealmConfigurator
   */
  private ClassRealm classRealm;


  /**
   * Sets the classrealm.
   *
   * @param classRealm the realm
   */
  public void setClassRealm(ClassRealm classRealm) {
    this.classRealm = classRealm;
  }


  /**
   * To create wurblet artifacts.
   */
  @Component
  private RepositorySystem repositorySystem;

  /**
   * To resolve the wurblet artifacts.
   */
  @Component
  private ArtifactResolver artifactResolver;

  /**
   * The local repository to resolve the artifacts.
   */
  @Parameter(defaultValue = "${localRepository}")
  private ArtifactRepository localRepository;




  /**
   * Total number of errors
   */
  private int totalErrors;


  @Override
  public void execute() throws MojoExecutionException, MojoFailureException {

    // validate configuration
    validate();

    // setup the file charset
    determineEncoding();

    // get the verbosity
    determineVerbosity();

    // register source types
    registerSourceTypes();

    // process properties
    exportExtraProperties(createExtraProperties());

    // setup resource directories for detecting wurb-files
    findResourceDirs();

    // update the classloader with wurbletDependencies
    updateClassLoader();

    // create any missing directories
    if (!wurbelDir.exists()) {
      if (wurbelDir.getPath().contains("${")) {
        getLog().warn("wurbelDir " + wurbelDir + " contains undefined variable -> skipped");
        return;
      }
      getLog().info("creating " + wurbelDir);
      wurbelDir.mkdirs();
    }
    if (!wurbelDir.isDirectory()) {
      throw new MojoExecutionException(wurbelDir + " is not a directory");
    }
    if (!getAnalyzeDir().exists()) {
      if (getAnalyzeDir().getPath().contains("${")) {
        getLog().warn("analyzeDir " + getAnalyzeDir() + " contains undefined variable -> skipped");
        return;
      }
      getLog().info("creating " + getAnalyzeDir());
      getAnalyzeDir().mkdirs();
    }
    if (!getAnalyzeDir().isDirectory()) {
      throw new MojoExecutionException(getAnalyzeDir() + " is not a directory");
    }


    TreeSet<Integer> collectedPhases = new TreeSet<>();
    int phase = 0;    // phase 0 is heredocs only (no wurblets processed -> this will update the model first)

    for (;;) {

      boolean hereDocsUpdated = true;

      while (hereDocsUpdated)  {   // until no more here docs updated

        totalErrors = 0;
        hereDocsUpdated = false;
        HeapFileFactory.initialize();   // clear any heapfiles generated in previous hereDocs loop

        if (filesets != null && filesets.size() > 0) {
          // explicit filesets given instead of source dir
          int count = 0;    // fileset count
          for (FileSet fileSet: filesets) {
            if (wurbelFileSet(fileSet, phase, collectedPhases)) {
              hereDocsUpdated = true;
              if (!dryRun) {
                break;
              }
            }
            else  {
              count++;
              if (totalErrors > 0) {
                int skipped = filesets.size() - count;
                if (skipped > 0) {
                  getLog().warn("remaining filesets ignored due to wurbel errors: " + skipped);
                }
                break;    // don't process any further filesets because they may depend on each other
              }
            }
          }
        }
        else {
          // all from source dir with default java-extension
          if (getSourceDir().isDirectory() && getSourceDir().list().length > 0) {
            final FileSet fs = new FileSet();
            fs.setDirectory(getSourceDir().getPath());
            fs.addInclude("**/*" + Constants.JAVA_SOURCE_EXTENSION);
            if (wurbelFileSet(fs, phase, collectedPhases)) {
              hereDocsUpdated = true;
            }
          }
          else {
            getLog().warn("no or empty wurbel.sourceDir " + getSourceDir().getAbsolutePath());
          }
        }

        if (dryRun) {
          break;
        }

        if (hereDocsUpdated) {
          getLog().info("some heredocs were updated -> starting over");
        }
      }

      Integer nextPhase = collectedPhases.higher(phase);
      if (totalErrors > 0 || nextPhase == null) {
        break;
      }
      phase = nextPhase;
    }

    if (totalErrors > 0) {
      throw new MojoFailureException(totalErrors + " wurbel errors");
    }
  }


  /**
   * Creates a {@link Wurbler}.
   *
   * @param filename the full pathname of the java-file
   * @param wurbFilename optional wurblet properties file, null to check in same dir
   * @param wurbletPath the list of package names to load wurblets from (if wurblet name is not absolute)
   * @param analyzeDir the list of directories wurblets load extra information from (usually from apt-runs)
   * @param verbosity the verbosity
   * @param logger the logger (can also be used by the wurblets)
   * @param errorsSoFar a set of errors logged so far, null if no suppression of repeating errors
   * @param dryRun dry run
   * @return the wurbler
   * @throws WurbelException if loading the wurb-file failed
   */
  public Wurbler createWurbler(String filename, String wurbFilename, String[] wurbletPath, String analyzeDir,
                               Logger logger, Verbosity verbosity, Set<String> errorsSoFar,
                               boolean dryRun) throws WurbelException {
    return new SourceWurbler(
            filename,
            wurbFilename,
            wurbletPath,
            analyzeDir,
            logger,
            verbosity,
            errorsSoFar,
            dryRun);
  }


  /**
   * Wurbel all files in a fileset.
   *
   * @param fileSet the set of files
   * @param phase the wurbel phase, 0 for heredocs, wurblets start at 1
   * @param collectedPhases wurbeled phases so far
   * @return true if heredocs were updated (needs another run)
   * @throws MojoExecutionException
   */
  private boolean wurbelFileSet(FileSet fileSet, int phase, Set<Integer> collectedPhases) throws MojoExecutionException {

    if (fileSet.getDirectory() == null) {
      // directory missing: use sourceDir as default
      fileSet.setDirectory(getSourceDir().getAbsolutePath());
    }

    String dirName;
    try {
      dirName = new File(fileSet.getDirectory()).getCanonicalPath();
    }
    catch (IOException ex) {
      throw new MojoExecutionException("cannot determine canonical path of " + fileSet.getDirectory(), ex);
    }

    if (verbosityLevel.isDebug()) {
      getLog().info("wurbelizing files in " + dirName);
    }

    int wurbeledFilesCount  = 0;
    int updatedFilesCount   = 0;
    int wurbletCount        = 0;
    int errorFilesCount     = 0;
    boolean hereDocsUpdated = false;

    String resourceDirName = getResourceDirName(dirName);
    Set<String> processedFiles = new HashSet<>();

    String[] names = new FileSetManager(getLog(), verbosityLevel.isDebug()).getIncludedFiles(fileSet);
    // always sort alphabetically to provide a deterministic file order
    Arrays.sort(names);

    Set<String> errorsSoFar = new HashSet<>();

    for (String name: names) {

      // local copy, because not final
      String fileName = name;
      // path to source file
      String filePath = dirName + File.separator + fileName;
      // path to wurblet property file, if pathname points to a .wurb-file
      String wurbPath = null;

      // replace .wurb files from resources with their corresponding java file from sources.
      // makes only sense if filesets are being used.
      if (fileName.endsWith(Wurbler.WURBLET_PROPERTIES_EXTENSION)) {
        wurbPath = new File(filePath).getAbsolutePath();
        if (resourceDirName != null) {
          // wurb file resides in a resource-dir
          fileName = filePath.substring(resourceDirName.length() + 1);  // cut including trailing separator
          fileName = fileName.substring(0, fileName.length() - Wurbler.WURBLET_PROPERTIES_EXTENSION.length()); // cut extension
          fileName += Constants.JAVA_SOURCE_EXTENSION;
          filePath = getSourceDir().getAbsolutePath() + File.separator + fileName;
        }
        else  {
          // from source dir
          fileName = filePath.substring(0, filePath.length() - Wurbler.WURBLET_PROPERTIES_EXTENSION.length()); // cut extension
          fileName += Constants.JAVA_SOURCE_EXTENSION;
          filePath = new File(fileName).getAbsolutePath();
        }
      }

      if (processedFiles.add(filePath)) { // don't process twice!
        try {

          wurbeledFilesCount++;

          // set per file extra properties
          File file = new File(filePath);
          WurbelHelper.getExtraProperties().setProperty("currentDir", file.getParent());
          WurbelHelper.getExtraProperties().setProperty("currentFile", file.getName());

          Wurbler sourceWurbler = createWurbler(
                  filePath,
                  wurbPath,
                  wurbletPathsAsArray(),
                  getAnalyzeDir().getAbsolutePath(),
                  new MavenLogger(getLog()),
                  verbosityLevel,
                  errorsSoFar,
                  dryRun);

          // wurbelize the source file
          WurbelResult result = sourceWurbler.wurbel(phase, collectedPhases);

          wurbletCount += result.getWurbletCount();

          if (result.getErrors() > 0) {
            errorFilesCount++;
            getLog().warn(fileName + " generated with wurblet errors (" + result.getErrors() + ")");
          }
          else {
            if (result.getUpdateType() == WurbelResult.UpdateType.UPDATED) {
              updatedFilesCount++;
              // file has been modified without errors
              String msg = fileName + (wurbPath == null ? "" : (" (" + wurbPath + ")"));
              if (verbosityLevel.isDebug()) {
                getLog().info(">>> " + msg + " <<< UPDATED!");
              }
              else if (verbosityLevel.isInfo()) {
                getLog().info(msg);
              }
            }
            else if (result.getUpdateType() == WurbelResult.UpdateType.HEREDOCS) {
              hereDocsUpdated = true;
            }
          }
        }
        catch (WurbelException wx) {
          if (wx.isSourceInfoIncluded()) {
            throw new MojoExecutionException(wx.getMessage(), wx);
          }
          else {
            throw new MojoExecutionException("source " + fileName + " wurbeled with errors", wx);
          }
        }
        catch (SourceException | RuntimeException ex) {
          throw new MojoExecutionException("unable to wurbel source " + fileName, ex);
        }
      }
    }

    if (phase > 0) {
      getLog().info(getPathRelativeToBasedir(new File(dirName).getAbsolutePath()) + ", phase " + phase + ": " +
                    wurbletCount + " wurblet" + (wurbletCount == 1 ? "" : "s") + " in " +
                    wurbeledFilesCount + " file" + (wurbeledFilesCount == 1 ? "" : "s") + " wurbeled, " +
                    updatedFilesCount + " updated, " +
                    errorFilesCount + " error" + (errorFilesCount == 1 ? "" : "s"));
    }

    totalErrors += errorFilesCount;

    return hereDocsUpdated;
  }



  /**
   * Gets the wurblet paths.
   *
   * @return the paths as a string array
   */
  private String[] wurbletPathsAsArray() {
    return wurbletPaths.toArray(new String[wurbletPaths.size()]);
  }



  /**
   * Registers all known source types.<br>
   * By default the {@link JavaSourceType} is registered.
   */
  protected void registerSourceTypes() {
    SourceWurbler.registerSourceType(new JavaSourceType());
  }



  /**
   * Creates the extra properties.
   *
   * @return the properties
   */
  @Override
  protected Properties createExtraProperties() {

    Properties props = super.createExtraProperties();
    props.setProperty("wurbelDir", wurbelDir.getAbsolutePath());

    if (wurbletProperties != null) {
      Properties tmpProps = new Properties();
      Enumeration<?> keys = wurbletProperties.keys();
      while (keys.hasMoreElements())  {
        Object key = keys.nextElement();
        if (key instanceof String)  {
          Object value = wurbletProperties.get(key);
          if (value instanceof String)  {
            tmpProps.setProperty((String) key, (String) value);
          }
        }
      }
      // next round: evaluate expressions
      keys = tmpProps.keys();
      while (keys.hasMoreElements())  {
        Object key = keys.nextElement();
        if (key instanceof String)  {
          Object value = wurbletProperties.get(key);
          if (value instanceof String)  {
            String strValue = WurbelHelper.translateVariables((String) value, props);
            props.setProperty((String) key, strValue);
          }
        }
      }
    }

    return props;
  }


  /**
   * Checks mandatory params.<br>
   *
   * @throws MojoExecutionException if validation fails.
   */
  protected void validate() throws MojoExecutionException {
    if (getSourceDir() == null) {
      throw new MojoExecutionException("missing wurbel.sourceDir");
    }
    if (getAnalyzeDir() == null) {
      throw new MojoExecutionException("missing wurbel.analyzeDir");
    }
    if (wurbelDir == null) {
      throw new MojoExecutionException("missing wurbel.wurbelDir");
    }
    if (wurbletPaths == null) {
      throw new MojoExecutionException("missing wurbletPaths");
    }
    if (wurbletPaths.isEmpty()) {
        throw new MojoExecutionException("wurbletPaths is empty");
    }
  }




  @SuppressWarnings("unchecked")
  private void updateClassLoader() {

    if (wurbletDependencies != null) {
      Set<Artifact> wurbletArtifacts = new HashSet<>();

      for (Dependency dep : wurbletDependencies) {

        Artifact artifact = repositorySystem.createArtifactWithClassifier(
                dep.getGroupId(), dep.getArtifactId(), dep.getVersion(), dep.getType(), dep.getClassifier());

        ArtifactResolutionRequest artifactRequest = new ArtifactResolutionRequest()
                .setArtifact(artifact)
                .setResolveTransitively(true)
                .setLocalRepository(localRepository)
                .setRemoteRepositories(project.getRemoteArtifactRepositories())
                .setOffline(true)
                .setForceUpdate(false)
                .setManagedVersionMap(project.getManagedVersionMap());

        Set<Artifact> resolvedArtifacts = artifactResolver.resolve(artifactRequest).getArtifacts();

        if (resolvedArtifacts.isEmpty()) {
          getLog().error("cannot resolve artifact " + artifact);
        }
        else {
          wurbletArtifacts.addAll(resolvedArtifacts);
          if (verbosityLevel.isDebug()) {
            for (Artifact resolvedArtifact: resolvedArtifacts) {
              getLog().debug("wurblet artifact " + resolvedArtifact + " added");
            }
          }
        }
      }

      // add all the jars we just downloaded to the new child realm
      for (Artifact artifact : wurbletArtifacts) {
        try {
          URL url = artifact.getFile().toURI().toURL();
          classRealm.addURL(url);
          if (verbosityLevel.isDebug()) {
            getLog().info("added to classpath: " + url);
          }
        }
        catch (MalformedURLException ex) {
          getLog().error("cannot determine URL for " + artifact.getFile(), ex);
        }
      }

      // make the child realm the ContextClassLoader
      Thread.currentThread().setContextClassLoader(classRealm);
    }
  }

}
