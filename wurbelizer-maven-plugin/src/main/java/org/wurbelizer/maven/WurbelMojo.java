package org.wurbelizer.maven;

import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.Parameter;
import org.apache.maven.plugins.annotations.ResolutionScope;

import java.io.File;

/**
 * Wurbel sources.<br>
 * Scans the sources for &#64;wurblet anchors and executes the wurblets.
 * The generated code from the wurblets is merged into the sources.
 *
 * @author harald
 */
@Mojo(name = "wurbel",
      defaultPhase = LifecyclePhase.PROCESS_SOURCES,
      configurator = "set-classrealm",
      requiresDependencyResolution = ResolutionScope.COMPILE_PLUS_RUNTIME)
public class WurbelMojo extends AbstractWurbelMojo {

  /**
   * Directory holding the sources to be wurbelized.<br>
   * Defaults to all java sources of the current project.
   * If this is not desired, filesets must be used.
   */
  @Parameter(defaultValue = "${project.build.sourceDirectory}",
             property = "wurbel.sourceDir",
             required = true)
  private File sourceDir;

  /**
   * Directory for additional files generated by preceeding phases
   * provided for wurblets.
   */
  @Parameter(defaultValue = "${project.build.directory}/analyze",
             property = "wurbel.analyzeDir",
             required = true)
  private File analyzeDir;

  @Override
  public File getSourceDir() {
    return sourceDir;
  }

  @Override
  public File getAnalyzeDir() {
    return analyzeDir;
  }

}
